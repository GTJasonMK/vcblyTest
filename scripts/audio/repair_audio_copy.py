#!/usr/bin/env python3
"""Create a corrected audio directory by copying from the original generated set.

This script does not modify the original audio directory. It reads the repaired
matching metadata from .audio_work/matched_cards.json and copies the source file
with the same video-record prefix from .audio_work/word_audio_matched_before_repair
to word_audio_matched_fixed with the corrected word suffix.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = ROOT / ".audio_work" / "word_audio_matched_before_repair"
TARGET_DIR = ROOT / "word_audio_matched_fixed"
MATCHED_FILE = ROOT / ".audio_work" / "matched_cards.json"
MANIFEST_JS = ROOT / "data" / "audio_manifest.js"
MANIFEST_FIXED_JSON = ROOT / ".audio_work" / "matched_cards_fixed_copy.json"


def find_source(prefix: int) -> Path:
    matches = sorted(SOURCE_DIR.glob(f"{prefix:04d}_*.m4a"))
    if len(matches) != 1:
        raise RuntimeError(f"expected one source file for {prefix:04d}, found {len(matches)}")
    return matches[0]


def write_manifest(records: list[dict]) -> None:
    by_word_index: dict[str, str] = {}
    by_word: dict[str, str] = {}
    for record in records:
        path = record["audio"]
        by_word_index[str(record["wordIndex"])] = path
        by_word.setdefault(record["word"], path)

    lines = [
        "// Generated by repair_audio_copy.py. Do not edit by hand.",
        f"var AUDIO_MANIFEST_BY_WORD_INDEX = {json.dumps(by_word_index, ensure_ascii=False, indent=2)};",
        f"var AUDIO_MANIFEST = {json.dumps(by_word, ensure_ascii=False, indent=2)};",
        "",
    ]
    MANIFEST_JS.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--overwrite", action="store_true", help="allow writing into an existing target directory")
    args = parser.parse_args()

    if not SOURCE_DIR.exists():
        raise SystemExit(f"missing source directory: {SOURCE_DIR}")
    if not MATCHED_FILE.exists():
        raise SystemExit(f"missing repaired metadata: {MATCHED_FILE}")
    if TARGET_DIR.exists() and not args.overwrite:
        raise SystemExit(f"target exists: {TARGET_DIR}; pass --overwrite or choose a clean directory")

    TARGET_DIR.mkdir(exist_ok=True)

    payload = json.loads(MATCHED_FILE.read_text(encoding="utf-8"))
    fixed_records: list[dict] = []
    copied = 0
    skipped = 0

    for record in payload["records"]:
        if record.get("skipManifest"):
            skipped += 1
            continue

        source = find_source(record["videoIndex"])
        filename = Path(record["audio"]).name
        target = TARGET_DIR / filename
        shutil.copy2(source, target)

        fixed = dict(record)
        fixed["audio"] = f"{TARGET_DIR.name}/{filename}"
        fixed_records.append(fixed)
        copied += 1

        if copied % 500 == 0 or copied == 1:
            print(f"copied {copied} files...")

    fixed_payload = dict(payload)
    fixed_payload["outputDir"] = TARGET_DIR.name
    fixed_payload["recordCount"] = len(fixed_records)
    fixed_payload["records"] = fixed_records
    MANIFEST_FIXED_JSON.write_text(json.dumps(fixed_payload, ensure_ascii=False, indent=2), encoding="utf-8")
    write_manifest(fixed_records)

    print(f"Copied {copied} corrected files -> {TARGET_DIR}")
    print(f"Skipped {skipped} duplicate/unmapped source records")
    print(f"Wrote {MANIFEST_FIXED_JSON}")
    print(f"Wrote {MANIFEST_JS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
